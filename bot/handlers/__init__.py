# IMPORTANT: the filter-less catch-all `_index_message` must be registered AFTER
# every command handler — aiogram stops on the first matching handler, so a
# catch-all registered earlier would swallow /tip, /rain and any other command.
# Import order alone is too fragile (formatters re-sort imports), so the
# registration is done explicitly here, at the very end of the package init.
_index_message = router.message()(_index_message)

